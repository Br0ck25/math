// Draws the Adventure world pictures listed in scripts/world-art.mjs into art/world/<id>.svg.   node scripts/make-world-art.mjs
// A file that already exists WITHOUT the generated marker is a hand-made picture and is never overwritten.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { WORLD } from './world-art.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'art/world');
const MARK = '<!-- generated by scripts/make-world-art.mjs -->';
export const worldSvg = (id) => WORLD[id].replace('<svg ', MARK + '<svg ');
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(dir, { recursive: true });
  let wrote = 0, kept = 0;
  Object.keys(WORLD).forEach((id) => {
    const file = path.join(dir, id + '.svg');
    if (fs.existsSync(file) && !fs.readFileSync(file, 'utf8').includes('generated by scripts/make-world-art.mjs')) { kept++; return; }
    fs.writeFileSync(file, worldSvg(id));
    wrote++;
  });
  console.log('drew ' + wrote + ' world pictures, kept ' + kept + ' hand-made ones');
}
