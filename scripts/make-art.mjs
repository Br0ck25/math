// Draws the pictures listed in scripts/art/specs.mjs into art/buddies/<id>.svg.   node scripts/make-art.mjs
// A file that already exists WITHOUT the generated marker is a hand-made picture from the owner and is never overwritten.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { palette, wrap, ACC } from './art/lib.mjs';
import { mammals } from './art/mammals.mjs';
import { birds } from './art/birds.mjs';
import { reptiles } from './art/reptiles.mjs';
import { sea } from './art/sea.mjs';
import { bugs } from './art/bugs.mjs';
import { other } from './art/other.mjs';
import { SPECS } from './art/specs.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'art/buddies');
const SPECIES = { ...mammals, ...birds, ...reptiles, ...sea, ...bugs, ...other };
export function draw([id, sp, color, x = {}]) {
  const make = SPECIES[sp];
  if (!make) throw new Error(id + ': unknown species ' + sp);
  const p = palette(color, x.pal || {});
  const r = make(p, x.o || {});
  const head = x.acc ? ACC[x.acc](r.a) : '';
  if (x.acc && !ACC[x.acc]) throw new Error(id + ': unknown accessory ' + x.acc);
  return wrap(r.svg + head);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(dir, { recursive: true });
  let wrote = 0, kept = 0;
  SPECS.forEach((spec) => {
    const file = path.join(dir, spec[0] + '.svg');
    if (fs.existsSync(file) && !fs.readFileSync(file, 'utf8').includes('generated by scripts/make-art.mjs')) { kept++; return; }
    fs.writeFileSync(file, draw(spec));
    wrote++;
  });
  console.log('drew ' + wrote + ' pictures, kept ' + kept + ' hand-made ones');
}
