// The generated pictures (scripts/make-art.mjs): every buddy and boss has its own look, and the files are valid and current.
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { launch, loadWorker, fakeKV, openGame } from './helpers.mjs';
import { SPECS } from '../scripts/art/specs.mjs';
import { draw } from '../scripts/make-art.mjs';

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../art/buddies');
// Licensed characters whose pictures come from the owner: until they arrive they may share an emoji with another buddy.
const WAITING = ['toon_bugs', 'secret_206', 'secret_208', 'secret_209', 'mythic_ron', 'mythic_barbie', 'mythic_lisa', 'secret_202', 'mythic_sirius', 'mythic_fawkes', 'mythic_buckbeak'];

let browser, page, errors;
before(async () => {
  browser = await launch();
  ({ page, errors } = await openGame(browser, await loadWorker(), { MATH_KV: fakeKV() }, { fast: true }));
});
after(async () => { await browser.close(); });

test('no two buddies or bosses look the same: each has its own picture or its own emoji (licensed characters still waiting for art excepted)', async () => {
  const rows = await page.evaluate(() => allBuddies().map((b) => ({ id: b.id, name: b.name, art: !!BUDDY_ART[b.id], emoji: b.emoji || b.icon })));
  const byEmoji = {};
  rows.filter((r) => !r.art).forEach((r) => (byEmoji[r.emoji] = byEmoji[r.emoji] || []).push(r));
  const clash = Object.keys(byEmoji).map((e) => byEmoji[e].filter((r) => WAITING.indexOf(r.id) === -1)).filter((g) => g.length > 1).map((g) => g.map((r) => r.name).join(' = '));
  assert.deepEqual(clash, [], 'these share an emoji: draw one in scripts/art/specs.mjs, or add art/buddies/<id>.svg');
  const bosses = await page.evaluate(() => monstersList.filter((m) => !m.icon.startsWith('<')).map((m) => m.name + '|' + m.icon));          // a boss with a picture is its own
  const seen = {}, bossClash = [];
  bosses.forEach((b) => { const [n, e] = b.split('|'); if (seen[e]) bossClash.push(n + ' = ' + seen[e]); seen[e] = n; });
  assert.deepEqual(bossClash, [], 'two bosses share an emoji');
});

test('every generated picture is a different animal: no two buddies or bosses share a species drawing', async () => {
  const bySpecies = {};
  SPECS.forEach((s) => (bySpecies[s[1]] = bySpecies[s[1]] || []).push(s[0]));
  const dupes = Object.keys(bySpecies).filter((k) => bySpecies[k].length > 1).map((k) => k + ': ' + bySpecies[k].join(', '));
  assert.deepEqual(dupes, [], 'give each buddy its own animal (a new template in scripts/art/*2.mjs), not just a new colour');
});

test('every spec is for a real buddy, the files are valid pictures, and they are up to date with the generator', async () => {
  const ids = await page.evaluate(() => allBuddies().map((b) => b.id));
  const bad = [];
  SPECS.forEach((spec) => {
    const id = spec[0], f = path.join(dir, id + '.svg');
    if (ids.indexOf(id) === -1) bad.push(id + ': no such buddy');
    else if (!fs.existsSync(f)) bad.push(id + ': file missing (run node scripts/make-art.mjs)');
    else {
      const text = fs.readFileSync(f, 'utf8');
      if (text.includes('generated by scripts/make-art.mjs') && text !== draw(spec)) bad.push(id + ': out of date (run node scripts/make-art.mjs)');
    }
  });
  assert.deepEqual(bad, []);
  assert.equal(new Set(SPECS.map((s) => s[0])).size, SPECS.length, 'a buddy is listed twice');
  const parsed = await page.evaluate((files) => files.map(([id, text]) => {
    const doc = new DOMParser().parseFromString(text, 'image/svg+xml');
    const root = doc.documentElement;
    return [id, doc.getElementsByTagName('parsererror').length === 0 && root.getAttribute('viewBox') === '0 0 100 100' && !/<script|onload|href=|<text|<image/i.test(text)];
  }).filter(([, ok]) => !ok).map(([id]) => id), SPECS.map((s) => [s[0], fs.readFileSync(path.join(dir, s[0] + '.svg'), 'utf8')]));
  assert.deepEqual(parsed, [], 'invalid, or contains something the pictures must not have');
});

test('the generated pictures are small enough for the page (each under 8 KB) and none of the licensed characters was drawn', async () => {
  const big = SPECS.filter((s) => fs.statSync(path.join(dir, s[0] + '.svg')).size > 8 * 1024).map((s) => s[0]);
  assert.deepEqual(big, []);
  assert.deepEqual(SPECS.map((s) => s[0]).filter((id) => WAITING.indexOf(id) !== -1), [], 'licensed characters must come from the owner');
});

test('no errors', () => { assert.deepEqual(errors, []); });
